/**
 * Helper to get a translation by dot notation path with fallback to English.
 */
export function t(keyPath, lang = 'en') {
  const currentLang = translations[lang] || translations.en;
  const fallback = translations.en;

  const parts = keyPath.split('.');
  
  let val = currentLang;
  for (const part of parts) {
    if (val && typeof val === 'object' && part in val) {
      val = val[part];
    } else {
      val = null;
      break;
    }
  }

  if (val != null && typeof val === 'string') {
    return val;
  }

  // Fallback to English
  let fbVal = fallback;
  for (const part of parts) {
    if (fbVal && typeof fbVal === 'object' && part in fbVal) {
      fbVal = fbVal[part];
    } else {
      fbVal = null;
      break;
    }
  }

  return (fbVal != null && typeof fbVal === 'string') ? fbVal : keyPath;
}
